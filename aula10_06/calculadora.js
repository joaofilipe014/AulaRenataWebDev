function somar(a,b){
    return(a + b);
}

function subtrair(a,b){
    return(a - b);
}

function dividir(a,b){
    return(a/b);
}

function multiplicar(a,b){
    return(a*b)
}


console.log("Soma: ",somar(10,5))
console.log("Subtrair: ",subtrair(20,10))
console.log("Dividir: ",dividir(100,3.3))
console.log("Multiplicar: ",multiplicar(50,3))